//! Compiles src/spec.json into Rust constructors so command metadata is not
//! parsed at runtime. The JSON stays the single source of truth; the generated
//! code must match `serde_json::from_str::<CommandSpec>` exactly (see the parity
//! test in src/spec.rs).
use serde_json::{Map, Value};
use std::{env, fmt::Write as _, fs, path::PathBuf};

const SPEC: &str = "src/spec.json";

fn main() {
    println!("cargo:rerun-if-changed={SPEC}");
    println!("cargo:rerun-if-changed=build.rs");
    let source = fs::read_to_string(SPEC).unwrap_or_else(|e| panic!("read {SPEC}: {e}"));
    let root: Value = serde_json::from_str(&source).unwrap_or_else(|e| panic!("parse {SPEC}: {e}"));
    let mut generator = Generator::default();
    let root_fn = generator.command(&root, "root");
    let mut out = String::from("// @generated by build.rs from src/spec.json. Do not edit.\n\n");
    let _ = writeln!(
        out,
        "fn generated_command_spec() -> CommandSpec {{\n    {root_fn}()\n}}\n"
    );
    out.push_str(&generator.functions);
    let path = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR")).join("command_spec.rs");
    fs::write(&path, out).unwrap_or_else(|e| panic!("write {}: {e}", path.display()));
}

#[derive(Default)]
struct Generator {
    functions: String,
    count: usize,
}

impl Generator {
    /// Emits one constructor function per command and returns its name.
    fn command(&mut self, value: &Value, path: &str) -> String {
        let obj = object(value, path);
        let children: Vec<String> =
            array(field(obj, "children", path), &format!("{path}.children"))
                .iter()
                .enumerate()
                .map(|(i, child)| {
                    let name = child.get("name").and_then(Value::as_str).unwrap_or("?");
                    self.command(child, &format!("{path}.children[{i}]({name})"))
                })
                .collect();
        let flags: Vec<String> = array(field(obj, "flags", path), &format!("{path}.flags"))
            .iter()
            .enumerate()
            .map(|(i, flag)| self::flag(flag, &format!("{path}.flags[{i}]")))
            .collect();
        let aliases: Vec<String> = array(field(obj, "aliases", path), &format!("{path}.aliases"))
            .iter()
            .enumerate()
            .map(|(i, alias)| string_lit(string(alias, &format!("{path}.aliases[{i}]"))))
            .collect();

        let fn_name = format!("command_spec_{}", self.count);
        self.count += 1;
        let s = |key: &str| string_lit(string(field(obj, key, path), &format!("{path}.{key}")));
        let b = |key: &str| boolean(field(obj, key, path), &format!("{path}.{key}"));
        let b_default = |key: &str| {
            obj.get(key)
                .map(|v| boolean(v, &format!("{path}.{key}")))
                .unwrap_or(false)
        };
        let operation = operation(string(
            field(obj, "operation", path),
            &format!("{path}.operation"),
        ));
        let args = args(field(obj, "args", path), &format!("{path}.args"));
        let _ = write!(
            self.functions,
            "fn {fn_name}() -> CommandSpec {{
    CommandSpec {{
        name: {name},
        operation: Operation::{operation},
        disable_flags_in_use_line: {disable_flags_in_use_line},
        r#use: {use_},
        short: {short},
        long: {long},
        example: {example},
        aliases: vec![{aliases}],
        flags: vec![{flags}],
        children: vec![{children}],
        args: {args},
        silence_usage: {silence_usage},
        requires_profile: {requires_profile},
        wrapped_preflight: {wrapped_preflight},
        hidden: {hidden},
    }}
}}

",
            name = s("name"),
            disable_flags_in_use_line = b_default("disable_flags_in_use_line"),
            use_ = s("use"),
            short = s("short"),
            long = s("long"),
            example = s("example"),
            aliases = aliases.join(", "),
            flags = flags.join(", "),
            children = children
                .iter()
                .map(|c| format!("{c}()"))
                .collect::<Vec<_>>()
                .join(", "),
            silence_usage = b("silence_usage"),
            requires_profile = b("requires_profile"),
            wrapped_preflight = b("wrapped_preflight"),
            hidden = b_default("hidden"),
        );
        fn_name
    }
}

fn flag(value: &Value, path: &str) -> String {
    let obj = object(value, path);
    let s = |key: &str| string_lit(string(field(obj, key, path), &format!("{path}.{key}")));
    let kind = match string(field(obj, "kind", path), &format!("{path}.kind")) {
        "string" => "String",
        "bool" => "Bool",
        "int" => "Int",
        "strings" => "Strings",
        other => panic!("{path}.kind: unknown flag kind {other:?}"),
    };
    format!(
        "FlagSpec {{ name: {}, shorthand: {}, kind: FlagKind::{kind}, default: {}, usage: {} }}",
        s("name"),
        s("shorthand"),
        json_value(field(obj, "default", path), &format!("{path}.default")),
        s("usage"),
    )
}

fn args(value: &Value, path: &str) -> String {
    let obj = object(value, path);
    let kind = match string(field(obj, "kind", path), &format!("{path}.kind")) {
        "arbitrary" => "Arbitrary",
        "exact" => "Exact",
        "max" => "Max",
        "min" => "Min",
        "range" => "Range",
        "none" => "None",
        "profile_add" => "ProfileAdd",
        other => panic!("{path}.kind: unknown args kind {other:?}"),
    };
    let counts: Vec<String> = obj
        .get("counts")
        .map(|v| array(v, &format!("{path}.counts")))
        .unwrap_or(&[])
        .iter()
        .enumerate()
        .map(|(i, n)| {
            let n = n
                .as_u64()
                .unwrap_or_else(|| panic!("{path}.counts[{i}]: expected unsigned integer"));
            format!("{n}usize")
        })
        .collect();
    format!(
        "ArgsRule {{ kind: ArgsKind::{kind}, counts: vec![{}] }}",
        counts.join(", ")
    )
}

fn operation(name: &str) -> &'static str {
    match name {
        "root" => "Root",
        "help" => "Help",
        "version" => "Version",
        "agent" => "Agent",
        "status" => "Status",
        "metadata" => "Metadata",
        "ingest_files" => "IngestFiles",
        "observe" => "Observe",
        "completion_group" => "CompletionGroup",
        "administration" => "Administration",
        "deferred" => "Deferred",
        other => panic!("unknown operation {other:?}"),
    }
}

/// Emits an expression building the same `serde_json::Value` the runtime parser
/// would produce. Only integers are accepted for numbers: the runtime crate uses
/// `arbitrary_precision`, so a float or non-canonical literal could not be
/// reproduced exactly from here.
fn json_value(value: &Value, path: &str) -> String {
    match value {
        Value::Null => "Value::Null".into(),
        Value::Bool(b) => format!("Value::Bool({b})"),
        Value::Number(n) => {
            if let Some(n) = n.as_u64() {
                format!("Value::Number(serde_json::Number::from({n}u64))")
            } else if let Some(n) = n.as_i64() {
                format!("Value::Number(serde_json::Number::from({n}i64))")
            } else {
                panic!("{path}: only integer defaults are supported, found {n}")
            }
        }
        Value::String(s) => format!("Value::String({})", string_lit(s)),
        Value::Array(items) => {
            let items: Vec<String> = items
                .iter()
                .enumerate()
                .map(|(i, v)| json_value(v, &format!("{path}[{i}]")))
                .collect();
            format!("Value::Array(vec![{}])", items.join(", "))
        }
        Value::Object(map) => {
            let entries: Vec<String> = map
                .iter()
                .map(|(k, v)| {
                    format!(
                        "({}, {})",
                        string_lit(k),
                        json_value(v, &format!("{path}.{k}"))
                    )
                })
                .collect();
            format!(
                "Value::Object(serde_json::Map::from_iter([{}]))",
                entries.join(", ")
            )
        }
    }
}

/// `str`'s Debug output is a valid Rust string literal with all special and
/// non-printable characters escaped.
fn string_lit(s: &str) -> String {
    format!("String::from({s:?})")
}

fn field<'a>(obj: &'a Map<String, Value>, key: &str, path: &str) -> &'a Value {
    obj.get(key)
        .unwrap_or_else(|| panic!("{path}: missing field {key:?}"))
}

fn object<'a>(value: &'a Value, path: &str) -> &'a Map<String, Value> {
    value
        .as_object()
        .unwrap_or_else(|| panic!("{path}: expected object"))
}

fn array<'a>(value: &'a Value, path: &str) -> &'a [Value] {
    value
        .as_array()
        .map(Vec::as_slice)
        .unwrap_or_else(|| panic!("{path}: expected array"))
}

fn string<'a>(value: &'a Value, path: &str) -> &'a str {
    value
        .as_str()
        .unwrap_or_else(|| panic!("{path}: expected string"))
}

fn boolean(value: &Value, path: &str) -> bool {
    value
        .as_bool()
        .unwrap_or_else(|| panic!("{path}: expected bool"))
}
